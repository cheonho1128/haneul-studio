const { contextBridge, ipcRenderer, webUtils } = require('electron');
contextBridge.exposeInMainWorld('api', {
  openMediaDialog: () => ipcRenderer.invoke('media:open-dialog'),
  probe: p => ipcRenderer.invoke('media:probe', p),
  filmstrip: (p, d) => ipcRenderer.invoke('media:filmstrip', p, d),
  extractFrame: (p, t) => ipcRenderer.invoke('media:frame', p, t),
  waveform: p => ipcRenderer.invoke('media:waveform', p),
  saveProject: o => ipcRenderer.invoke('project:save', o),
  openProject: () => ipcRenderer.invoke('project:open'),
  fileExists: p => ipcRenderer.invoke('file:exists', p),
  openSrt: () => ipcRenderer.invoke('srt:open'),
  saveSrt: t => ipcRenderer.invoke('srt:save', t),
  chooseExport: () => ipcRenderer.invoke('export:choose'),
  startExport: o => ipcRenderer.invoke('export:start', o),
  cancelExport: () => ipcRenderer.invoke('export:cancel'),
  showInFolder: p => ipcRenderer.invoke('shell:show', p),
  onExportProgress: cb => ipcRenderer.on('export:progress', (_e, v) => cb(v)),
  onBeforeClose: cb => ipcRenderer.on('app:before-close', () => cb()),
  closeApp: () => ipcRenderer.invoke('app:close'),
  toggleDevTools: () => ipcRenderer.invoke('app:devtools'),
  getFont: url => ipcRenderer.invoke('font:get', url),
  readText: p => ipcRenderer.invoke('file:read-text', p),
  openLut: () => ipcRenderer.invoke('lut:open'),
  appVersion: () => ipcRenderer.invoke('app:version'),
  checkUpdate: () => ipcRenderer.invoke('update:check'),
  installUpdate: () => ipcRenderer.invoke('update:install'),
  restartApp: () => ipcRenderer.invoke('update:restart'),
  openUpdatePage: u => ipcRenderer.invoke('update:open', u),
  onUpdateProgress: cb => ipcRenderer.on('update:progress', (_e, v) => cb(v)),
  pathForFile: f => webUtils.getPathForFile(f),
});
