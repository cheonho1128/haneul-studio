const { _electron: electron } = require('playwright');
const path = require('path');
const F = p => path.join(__dirname, 'fixtures', p);
(async () => {
  const app = await electron.launch({ executablePath: require(path.join(__dirname, '..', 'node_modules', 'electron')), args: ['.', '--no-sandbox'], cwd: path.join(__dirname, '..') });
  const win = await app.firstWindow();
  const errors = []; win.on('pageerror', e => errors.push(String(e))); win.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  await win.waitForTimeout(1000);
  await win.evaluate(async (fx) => { await window.__studio.importPaths([fx.s, fx.a]); }, { s: F('scenes.mp4'), a: F('a.mp4') });
  await win.waitForTimeout(500);
  await win.evaluate(() => document.querySelectorAll('.media-item').forEach(el => el.dispatchEvent(new MouseEvent('dblclick', { bubbles: true }))));
  await win.waitForTimeout(1200);
  await win.click('[data-tab="effects"]');
  const dnd = (tileText, x) => win.evaluate(([tileText, x]) => {
    const tile = [...document.querySelectorAll('#libEffects .fx-tile, #libTransitions .fx-tile')].find(t => t.textContent.trim() === tileText && t.offsetParent);
    const dt = new DataTransfer();
    tile.dispatchEvent(new DragEvent('dragstart', { bubbles: true, dataTransfer: dt }));
    const tr = window.__studio.project.tracks.find(t => t.main);
    const row = document.querySelector(`.track[data-id="${tr.id}"]`); const r = row.getBoundingClientRect();
    row.dispatchEvent(new DragEvent('dragover', { bubbles: true, cancelable: true, clientX: r.left + x, clientY: r.top + 10, dataTransfer: dt }));
    const hl = document.querySelectorAll('.clip.fx-drop, .clip.fx-drop-start').length;
    row.dispatchEvent(new DragEvent('drop', { bubbles: true, cancelable: true, clientX: r.left + x, clientY: r.top + 10, dataTransfer: dt }));
    tile.dispatchEvent(new DragEvent('dragend', { bubbles: true, dataTransfer: dt }));
    return hl + ' ' + JSON.stringify(tr.clips.map(c => [(c.effects || []).map(e => e.type).join('+'), c.transitionIn && c.transitionIn.type]));
  }, [tileText, x]);
  console.log('drop effect on clip1', await dnd('4분할', 100));
  await win.click('[data-tab="transitions"]');
  console.log('drop transition near boundary', await dnd('원형 열기', 6 * 60 + 5));
  await win.waitForTimeout(300);
  // 크롭 + 배경 흐림 미리보기
  await win.evaluate(() => { const s = window.__studio; s.project.width = 720; s.project.height = 1280; const c = s.project.tracks.find(t => t.main).clips[0]; c.bg = { type: 'blur', amount: 60 }; c.crop = { l: 0.1, r: 0.1, t: 0, b: 0 }; c.effects = []; s.selectClip(c.id); s.seek(1); });
  await win.evaluate(() => window.dispatchEvent(new Event('resize')));
  await win.waitForTimeout(600);
  await win.click('.prop-tabs button[data-t="basic"]');
  await win.screenshot({ path: path.join(__dirname, 'ui15.png') });
  await win.evaluate(() => { const s = window.__studio; s.setPlaying(false); const c = s.project.tracks.find(t => t.main).clips[1]; s.selectClip(c.id); });
  await win.waitForTimeout(300);
  await win.click('.prop-tabs button[data-t="audio"]');
  await win.click('text=로봇');
  await win.click('text=효과 넣은 소리 미리 듣기');
  await win.waitForTimeout(2500);
  await win.screenshot({ path: path.join(__dirname, 'ui16.png') });
  await win.click('#btnExport'); await win.selectOption('#expFormat', 'gif'); await win.waitForTimeout(200);
  await win.screenshot({ path: path.join(__dirname, 'ui17.png') });
  await win.click('#expCancel');
  await win.click('#btnCloud'); await win.waitForTimeout(500);
  await win.screenshot({ path: path.join(__dirname, 'ui18.png') });
  console.log('errors', errors);
  app.process().kill('SIGKILL'); process.exit(0);
})().catch(e => { console.error(e); process.exit(1); });
