const { _electron: electron } = require('playwright');
const path = require('path');
const F = p => path.join(__dirname, 'fixtures', p);
(async () => {
  const app = await electron.launch({ executablePath: require(path.join(__dirname, '..', 'node_modules', 'electron')), args: ['.', '--no-sandbox'], cwd: path.join(__dirname, '..') });
  const win = await app.firstWindow();
  const errors = []; win.on('pageerror', e => errors.push(String(e))); win.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  await win.waitForTimeout(1000);
  await win.evaluate(async (fx) => { await window.__studio.importPaths([fx.s, fx.a]); }, { s: F('scenes.mp4'), a: F('a.mp4') });
  await win.waitForTimeout(500);
  await win.evaluate(() => document.querySelectorAll('.media-item').forEach(el => el.dispatchEvent(new MouseEvent('dblclick', { bubbles: true }))));
  await win.waitForTimeout(1200);
  await win.click('.clip.video >> nth=1');
  await win.click('.prop-tabs button[data-t="effects"]');
  await win.waitForTimeout(300);
  await win.hover('#props .fx-tile >> text=4분할');
  await win.waitForTimeout(900);
  await win.screenshot({ path: path.join(__dirname, 'ui11.png') });
  await win.click('#props .fx-tile >> text=4분할');
  await win.waitForTimeout(300);
  console.log('effects', await win.evaluate(() => JSON.stringify(window.__studio.project.tracks.flatMap(t => t.clips.map(c => c.effects || [])))));
  await win.click('.prop-tabs button[data-t="trans"]');
  await win.click('#props .fx-cats button >> text=도형');
  await win.hover('#props .fx-tile >> text=원형 열기');
  await win.waitForTimeout(1050);
  await win.screenshot({ path: path.join(__dirname, 'ui12.png') });
  await win.mouse.move(700, 300);
  await win.waitForTimeout(300);
  console.log('after leave trans', await win.evaluate(() => JSON.stringify(window.__studio.project.tracks.flatMap(t => t.clips.map(c => c.transitionIn && c.transitionIn.type)))));
  await win.click('#props .fx-tile >> text=시계 방향');
  console.log('after click trans', await win.evaluate(() => JSON.stringify(window.__studio.project.tracks.flatMap(t => t.clips.map(c => c.transitionIn && c.transitionIn.type)))));
  await win.click('[data-tab="effects"]');
  await win.waitForTimeout(300);
  await win.screenshot({ path: path.join(__dirname, 'ui13.png') });
  console.log('errors', errors);
  app.process().kill('SIGKILL'); process.exit(0);
})().catch(e => { console.error(e); process.exit(1); });
